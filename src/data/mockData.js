/**
 * Returns all cards that belong to a given column.
 * @param {string} columnId
 * @param {Array} cards
 * @returns {Array}
 */
export function getCardsByColumn(columnId, cards) {
  return cards
    .filter((card) => card.columnId === columnId && !card.archived)
    .sort((a, b) => a.position - b.position);
}
